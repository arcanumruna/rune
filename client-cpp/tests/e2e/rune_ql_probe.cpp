// tests/e2e/rune_ql_probe.cpp — Task 10 (0c #11 real-e2e gate) typed probe.
//
// SINGLE-NODE real-Aeron typed round-trip against a REAL rune-broker over REAL
// Aeron (default config, NOT in-process).  Unlike the 0b probe (which embedded a
// checked-in descriptor blob and generated its header at BUILD time), this 0c
// probe is driven entirely by the `rune` CLI:
//
//   docker/rune-ql-e2e.sh runs, INSIDE the client container, against the broker:
//     1. rune schema apply    tests/e2e/characters.rql --broker <node> --validate
//     2. rune schema generate characters --out <gen> --broker <node>
//        -> writes <gen>/characters.gen.h  (fingerprint == broker's stored schema)
//     3. g++ compiles THIS probe against that generated header + the prebuilt
//        rune_client_* static libs.
//     4. runs this probe.
//
// Because the header comes from `rune schema generate` (which fetches the broker's
// stored schema), openTopic<Characters>'s exact-fingerprint gate matches by
// construction — this is the whole point of the CLI-driven flow.
//
// This probe then:
//   - connect()                                    — real Aeron session
//   - openTopic<rune::gen::Characters>("characters") — EXACT-fingerprint gate
//   - send N typed records (set the `code` FixedStr[8] + var `name`)
//   - subscribe(from earliest) + decode each record
//   - ASSERT every field round-trips: id / userId / code[8] / name
//   - produce a MALFORMED raw record -> ASSERT SchemaValidationFailed (validate=ON)
//
// The topic is already defined (by `rune schema apply --validate` in step 1), so
// this probe does NOT defineTopic; it opens the existing validated topic.
//
// Environment:
//   RUNE_TARGET          — node client ingress channel (required)
//   RUNE_TARGET_STREAM   — int, default 1
//   RUNE_EGRESS          — this client's own egress channel (required)
//   RUNE_EGRESS_STREAM   — int, default 2
//   RUNE_DATA_DIR        — Aeron driver dir (required)
//   RUNE_RECORDS         — records to produce/consume, default 5
//   RUNE_TIMEOUT_MS      — per-operation timeout ms, default 15000
//
// Exit 0 AND prints "PROBE: OK" iff every leg passes; otherwise "PROBE: FAIL ..."
// to stderr + non-zero exit.  Bounded/time-independent waits everywhere (#16).

#include "../../examples/ExampleAuth.h"
#include "characters.gen.h"   // runtime-generated by `rune schema generate`

