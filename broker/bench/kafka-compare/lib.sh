#!/usr/bin/env bash
# Shared helpers: logging, broker/kafka lifecycle, JSON emission.
# Requires env.sh already sourced.

log()  { echo "[$(date +%H:%M:%S)] $*" >&2; }
die()  { echo "FATAL: $*" >&2; exit 1; }

# --------------------------------------------------------------------------
# JSON emission: append one result object (jsonl) to $RESULTS_RAW.
# Usage: emit_result <k=v> ... where values are already correct types.
# String keys we always quote; numeric keys are emitted raw.
# We build the object with python for correctness.
# --------------------------------------------------------------------------
emit_result() {
  python3 - "$@" <<'PY' >>"$RESULTS_RAW"
import json, sys
STRINGS = {"tool","scenario","tier","persistence","idle","notes","status"}
obj = {}
for kv in sys.argv[1:]:
    k, _, v = kv.partition("=")
    if k in STRINGS:
        obj[k] = v
    else:
        try:
            obj[k] = int(v)
        except ValueError:
            try: obj[k] = float(v)
            except ValueError: obj[k] = v
print(json.dumps(obj))
PY
}

# --------------------------------------------------------------------------
# Topics by DDL.  The brokers take no topic list: once a broker (or the cluster's
# leader) is up, the bench topic is created through the rune CLI ($RUNE_CLI).
# --------------------------------------------------------------------------
# rune_topic_ddl <name:partitions[:key=value...]> -> one Rune QL statement on stdout.
#   Options: tier=leader|majority|strict, durability=majority|all-in-sync, rf=N (replicas N).
#   e.g. "bench:8:tier=leader" -> "topic bench partitions 8 with (tier = leader);"
#   Anything else is refused (never silently dropped).
rune_topic_ddl() {
  local -a f; IFS=: read -ra f <<<"$1"
  [ "${#f[@]}" -ge 2 ] || { echo "bad topic spec '$1' (want name:partitions[:key=value...])" >&2; return 1; }
  local stmt="topic ${f[0]} partitions ${f[1]}" with="" replicas="" i kv
  for ((i = 2; i < ${#f[@]}; i++)); do
    kv="${f[$i]}"
    case "$kv" in
      tier=*|durability=*) with="${with:+$with, }${kv%%=*} = ${kv#*=}" ;;
      rf=*)                replicas=" replicas ${kv#rf=}" ;;
      *) echo "topic spec '$1': option '$kv' has no DDL mapping" >&2; return 1 ;;
    esac
  done
  echo "${stmt}${replicas}${with:+ with ($with)};"
}
# rune_create_topics <client_port> <spec>[,<spec>...] -> creates the topics through the broker at
#   127.0.0.1:<client_port>.  One fixed request id per call, so a retried run returns the original
#   results.  Retries (0.5 s) on NotLeader / Redirect / connect timeouts while the catalog leader
#   forms, bounded by RUNE_CREATE_TOPICS_DEADLINE_S (default 60); any other error fails at once.
rune_create_topics() {
  local port="$1" specs="$2" ddl="" spec s
  [ -x "$RUNE_CLI" ] || { log "rune CLI not found at RUNE_CLI=$RUNE_CLI (build rune-client-cpp)"; return 1; }
  local -a list; IFS=, read -ra list <<<"$specs"
  for spec in "${list[@]}"; do s="$(rune_topic_ddl "$spec")" || return 1; ddl="$ddl$s"$'\n'; done
  local rid; rid="$(od -An -N14 -tx1 /dev/urandom | tr -d ' \n')0000"
  local deadline=$((SECONDS + ${RUNE_CREATE_TOPICS_DEADLINE_S:-60})) out
  while :; do
    if out="$("$RUNE_CLI" ql -f - --request-id "$rid" --broker "127.0.0.1:${port}" <<<"$ddl" 2>&1)"; then
      log "topics created: ${specs}"; return 0
    fi
    if ! grep -qiE 'NotLeader|Redirect|timed out|connection refused|not connected|unreachable' <<<"$out"; then
      log "creating topics '${specs}' failed: $out"; return 1
    fi
    [ "$SECONDS" -lt "$deadline" ] || { log "topics '${specs}' not created within ${RUNE_CREATE_TOPICS_DEADLINE_S:-60}s: $out"; return 1; }
    sleep 0.5
  done
}

# --------------------------------------------------------------------------
# Authentication: a cluster key, the first admin and the `bench` user (Task 20)
# --------------------------------------------------------------------------
# The broker refuses to start without RUNE_CLUSTER_KEY_FILE.  Files under $RUNE_BENCH_AUTH_DIR (tmpfs, 0700):
#   cluster.key  (re)generated by rune_bench_auth_key for every cluster start - all nodes share it
#   otp, admin.pw, bench.pw   generated once, reused by every (fresh) cluster
rune_bench_gen_pw() {   # <file> : a 24-character alphanumeric password, mode 0600 (kept if present)
  [ -s "$1" ] && return 0
  ( umask 077; LC_ALL=C head -c 96 /dev/urandom | base64 | LC_ALL=C tr -dc 'A-Za-z0-9' | head -c 24 > "$1"; echo >> "$1" )
  [ "$(wc -c < "$1")" -ge 13 ] || { log "could not generate a password in $1"; return 1; }
}
rune_bench_auth_key() {   # (re)generates $RUNE_BENCH_AUTH_DIR/cluster.key with `rune security gen-cluster-key`
  [ -x "$RUNE_CLI" ] || { log "rune CLI not found at RUNE_CLI=$RUNE_CLI (build rune-client-cpp)"; return 1; }
  mkdir -p "$RUNE_BENCH_AUTH_DIR" && chmod 700 "$RUNE_BENCH_AUTH_DIR"
  rm -f "$RUNE_BENCH_AUTH_DIR/cluster.key"
  "$RUNE_CLI" security gen-cluster-key --out "$RUNE_BENCH_AUTH_DIR/cluster.key" >/dev/null || { log "gen-cluster-key failed"; return 1; }
  rune_bench_gen_pw "$RUNE_BENCH_AUTH_DIR/otp" && rune_bench_gen_pw "$RUNE_BENCH_AUTH_DIR/admin.pw" \
    && rune_bench_gen_pw "$RUNE_BENCH_AUTH_DIR/bench.pw"
}
# rune_bench_bootstrap <client_port> : on a fresh cluster with a leader: bootstrap `admin`, change its one-time password,
# create the role + user the clients and the CLI log in as ($RUNE_USER).  Retries (0.5 s) while the cluster forms.
rune_bench_bootstrap() {
  local port="$1" d="$RUNE_BENCH_AUTH_DIR" out rc
  local deadline=$((SECONDS + ${RUNE_BOOTSTRAP_DEADLINE_S:-90}))
  while :; do
    out="$("$RUNE_CLI" security bootstrap --admin admin --password-file "$d/otp" --cluster-key-file "$d/cluster.key" \
             --broker "127.0.0.1:${port}" 2>&1)"; rc=$?
    [ "$rc" -eq 0 ] && break
    if ! grep -qiE 'NotLeader|Redirect|timed out|connection refused|not connected|unreachable|not ready' <<<"$out" || [ "$SECONDS" -ge "$deadline" ]; then
      log "bootstrap failed (exit $rc): $out"; return 1
    fi
    sleep 0.5
  done
  ( umask 077
    printf "ALTER USER admin SET PASSWORD '%s';\n" "$(cat "$d/admin.pw")" > "$d/alter.rql"
    { echo "CREATE ROLE bench;"
      for op in READ WRITE CREATE ALTER DROP; do echo "GRANT $op ON TOPIC PREFIX '' TO ROLE bench;"; done
      echo "GRANT READ ON GROUP PREFIX '' TO ROLE bench;"
      echo "GRANT WRITE ON TRANSACTIONAL_ID PREFIX '' TO ROLE bench;"
      echo "GRANT DESCRIBE ON CLUSTER TO ROLE bench;"
      printf "CREATE USER %s WITH PASSWORD '%s';\n" "$RUNE_USER" "$(cat "$d/bench.pw")"
      echo "GRANT ROLE bench TO USER $RUNE_USER;"; } > "$d/bench.rql" )
  out="$("$RUNE_CLI" ql --user admin --password-file "$d/otp" -f "$d/alter.rql" --broker "127.0.0.1:${port}" 2>&1)" \
    || { rm -f "$d/alter.rql" "$d/bench.rql"; log "ALTER USER admin failed: $out"; return 1; }
  out="$("$RUNE_CLI" ql --user admin --password-file "$d/admin.pw" -f "$d/bench.rql" --broker "127.0.0.1:${port}" 2>&1)" \
    || { rm -f "$d/alter.rql" "$d/bench.rql"; log "creating the bench user failed: $out"; return 1; }
  rm -f "$d/alter.rql" "$d/bench.rql"
  log "authentication: admin bootstrapped, user '$RUNE_USER' created"
}

# --------------------------------------------------------------------------
# Rune broker lifecycle
# --------------------------------------------------------------------------
# The throughput clients read their topic table from RUNE_CLIENT_TOPIC_TABLE (renamed from the broker-era
# variable); a binary built before the rename would silently run on its default table.
rune_check_client_bins() {
  local b; for b in "$RUNE_PROD_BIN" "$RUNE_CONS_BIN"; do
    grep -qa RUNE_CLIENT_TOPIC_TABLE "$b" || { log "client binary $b predates RUNE_CLIENT_TOPIC_TABLE: rebuild rune-client-cpp"; return 1; }
  done
}

# rune_start_broker <workers> <topics_spec> [io_backend] [persistence]
#   topics_spec e.g. "bench:8:tier=strict"; persistence nvme|tmpfs selects the
#   LOG storage root (aeron IPC always lives on tmpfs scratch).
RUNE_BPID=""
rune_start_broker() {
  rune_check_client_bins || return 1
  local workers="$1" topics="$2" io="${3:-uring}" persistence="${4:-nvme}"
  local logdir; logdir="$(data_root "$persistence" rune-log)"
  local d="$WORK/rune"; rm -rf "$d" "$logdir"; mkdir -p "$d/a" "$logdir"
  rune_bench_auth_key || return 1   # authentication is ON: the broker needs a cluster key file
  pkill -9 -f "$RUNE_BROKER_BIN" 2>/dev/null; sleep 0.4
  log "rune broker: workers=$workers topics='$topics' io=$io"
  # shellcheck disable=SC2086
  env RUNE_CLUSTER_KEY_FILE="$RUNE_BENCH_AUTH_DIR/cluster.key" \
      RUNE_NODE_ID=1 RUNE_STORAGE_FORMAT=new RUNE_PEERS="1@127.0.0.1:${RUNE_CONSENSUS_PORT}:${RUNE_CLIENT_PORT}" \
      RUNE_CLIENT_ENDPOINT="0.0.0.0:${RUNE_CLIENT_PORT}" \
      RUNE_DATA_DIR="$logdir" RUNE_AERON_DIR="$d/a" RUNE_WORKERS="$workers" \
      RUNE_PER_WORKER_INGRESS=true RUNE_PER_WORKER_EGRESS=true \
      RUNE_IO_BACKEND="$io" RUNE_AERON_TERM_BUFFER_BYTES=33554432 \
      RUNE_WORKER_INGRESS_RING_BYTES=33554432 RUNE_WORKER_RETURN_RING_BYTES=33554432 \
      RUNE_WORKER_EGRESS_CONTROL_BASE_PORT="$RUNE_WORKER_EGRESS_BASE" \
      RUNE_WORKER_IDLE="${RUNE_WORKER_IDLE:-backoff}" RUNE_RUNTIME_IDLE="${RUNE_RUNTIME_IDLE:-backoff}" \
      RUNE_WORKER_MODE="${RUNE_WORKER_MODE:-legacy}" RUNE_RUNTIME_PLACEMENT="${RUNE_RUNTIME_PLACEMENT:-thread}" \
      RUNE_WORKER_CORE_BASE="${RUNE_WORKER_CORE_BASE:--1}" RUNE_LOG_LEVEL=info \
      $(pin "$CORES_BROKER") "$RUNE_BROKER_BIN" >"$d/broker.log" 2>&1 &
  RUNE_BPID=$!
  local i
  for i in $(seq 1 200); do
    # Ready when the workerpool is built (info log) OR the client endpoint is bound.
    if grep -qiE "WorkerPool built|is LEADER" "$d/broker.log" 2>/dev/null \
       || ss -lun 2>/dev/null | grep -q ":${RUNE_CLIENT_PORT} "; then
      sleep 1
      rune_bench_bootstrap "$RUNE_CLIENT_PORT" || return 1
      rune_create_topics "$RUNE_CLIENT_PORT" "$topics" || return 1
      log "rune broker ready"; return 0
    fi
    kill -0 "$RUNE_BPID" 2>/dev/null || { log "BROKER DIED"; tail -20 "$d/broker.log" >&2; return 1; }
    sleep 0.25
  done
  log "BROKER READY TIMEOUT"; tail -20 "$d/broker.log" >&2; return 1
}
rune_stop_broker() { [ -n "$RUNE_BPID" ] && kill -9 "$RUNE_BPID" 2>/dev/null; RUNE_BPID=""; pkill -9 -f "$RUNE_BROKER_BIN" 2>/dev/null; sleep 0.3; true; }

# --------------------------------------------------------------------------
# Kafka (KRaft single-node) lifecycle
# --------------------------------------------------------------------------
KAFKA_PID=""
kafka_start() {
  local persistence="${1:-nvme}"; local cores="${2:-$CORES_BROKER}"
  local logdir; logdir="$(data_root "$persistence" kafka-logs)"
  rm -rf "$logdir"; mkdir -p "$logdir"
  local cfg="$WORK/kraft.properties"
  local cid
  cid="$("$KAFKA_HOME"/bin/kafka-storage.sh random-uuid)"
  cat >"$cfg" <<EOF
process.roles=broker,controller
node.id=1
controller.quorum.voters=1@127.0.0.1:9093
listeners=PLAINTEXT://127.0.0.1:9092,CONTROLLER://127.0.0.1:9093
inter.broker.listener.name=PLAINTEXT
controller.listener.names=CONTROLLER
advertised.listeners=PLAINTEXT://127.0.0.1:9092
log.dirs=$logdir
num.network.threads=8
num.io.threads=16
offsets.topic.replication.factor=1
transaction.state.log.replication.factor=1
transaction.state.log.min.isr=1
EOF
  "$KAFKA_HOME"/bin/kafka-storage.sh format -t "$cid" -c "$cfg" >/dev/null 2>&1 || die "kafka-storage format failed"
  log "kafka start: logdir=$logdir"
  # shellcheck disable=SC2086
  env KAFKA_HEAP_OPTS="$KAFKA_HEAP" $(pin "$cores") \
      "$KAFKA_HOME"/bin/kafka-server-start.sh "$cfg" >"$WORK/kafka.log" 2>&1 &
  KAFKA_PID=$!
  local i
  for i in $(seq 1 120); do
    "$KAFKA_HOME"/bin/kafka-broker-api-versions.sh --bootstrap-server "$KAFKA_BOOTSTRAP" >/dev/null 2>&1 && { log "kafka ready"; return 0; }
    kill -0 "$KAFKA_PID" 2>/dev/null || { log "KAFKA DIED"; tail -30 "$WORK/kafka.log" >&2; return 1; }
    sleep 1
  done
  log "KAFKA READY TIMEOUT"; tail -30 "$WORK/kafka.log" >&2; return 1
}
kafka_stop() {
  "$KAFKA_HOME"/bin/kafka-server-stop.sh >/dev/null 2>&1
  [ -n "$KAFKA_PID" ] && { for _ in $(seq 1 30); do kill -0 "$KAFKA_PID" 2>/dev/null || break; sleep 0.5; done; kill -9 "$KAFKA_PID" 2>/dev/null; }
  KAFKA_PID=""; sleep 0.5; true
}
kafka_topic() {
  local name="$1" parts="$2"; shift 2
  "$KAFKA_HOME"/bin/kafka-topics.sh --bootstrap-server "$KAFKA_BOOTSTRAP" --create \
    --topic "$name" --partitions "$parts" --replication-factor 1 "$@" >/dev/null 2>&1 || true
}

# median of stdin numbers (one per line)
median() { python3 -c 'import sys;v=sorted(float(x) for x in sys.stdin if x.strip());print(0 if not v else v[len(v)//2])'; }
