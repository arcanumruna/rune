// tools/gen_unicode_lower.cpp
// gen_unicode_lower <UnicodeData.txt> <out.inc>: writes the two-stage Simple_Lowercase_Mapping table.
// Run ONCE per Unicode version; the output is committed as src/UnicodeLowerTable.inc.
#include <array>
#include <cstdint>
#include <cstdio>
#include <fstream>
#include <map>
#include <sstream>
#include <string>
#include <vector>

namespace {
constexpr uint32_t kCodePoints = 0x110000, kBlock = 128, kExpectedLines = 40116, kExpectedMappings = 1460;

uint32_t utf8Len(uint32_t cp) { return cp < 0x80 ? 1 : cp < 0x800 ? 2 : cp < 0x10000 ? 3 : 4; }
}

int main(int argc, char** argv) {
    if (argc != 3) { std::fprintf(stderr, "usage: gen_unicode_lower <UnicodeData.txt> <out.inc>\n"); return 1; }
    std::ifstream in(argv[1], std::ios::binary);
    if (!in) { std::fprintf(stderr, "cannot open %s\n", argv[1]); return 1; }
    std::vector<int32_t> delta(kCodePoints, 0);
    std::array<uint32_t, 5> maxLen{};
    uint32_t lines = 0, mappings = 0;
    std::string line;
    while (std::getline(in, line)) {
        ++lines;
        std::vector<std::string> fld;
        std::stringstream ss(line);
        std::string f;
        while (std::getline(ss, f, ';')) fld.push_back(f);
        if (line.back() == ';') fld.emplace_back();
        if (fld.size() != 15) { std::fprintf(stderr, "line %u: %zu fields\n", lines, fld.size()); return 1; }
        if (fld[13].empty()) continue;
        const uint32_t cp = uint32_t(std::stoul(fld[0], nullptr, 16)), lo = uint32_t(std::stoul(fld[13], nullptr, 16));
        delta[cp] = int32_t(lo) - int32_t(cp);
        ++mappings;
        const uint32_t sl = utf8Len(cp);
        if (utf8Len(lo) > maxLen[sl]) maxLen[sl] = utf8Len(lo);
    }
    if (lines != kExpectedLines || mappings != kExpectedMappings) {
        std::fprintf(stderr, "expected %u lines / %u mappings, got %u / %u\n", kExpectedLines, kExpectedMappings, lines, mappings);
        return 1;
    }

    std::vector<std::array<int32_t, kBlock>> blocks(1);   // block 0 = identity
    std::map<std::array<int32_t, kBlock>, uint16_t> seen{{blocks[0], 0}};
    std::vector<uint16_t> stage1(kCodePoints / kBlock);
    for (uint32_t b = 0; b < stage1.size(); ++b) {
        std::array<int32_t, kBlock> blk;
        for (uint32_t i = 0; i < kBlock; ++i) blk[i] = delta[b * kBlock + i];
        auto [it, fresh] = seen.try_emplace(blk, uint16_t(blocks.size()));
        if (fresh) blocks.push_back(blk);
        stage1[b] = it->second;
    }

    std::ofstream out(argv[2], std::ios::binary | std::ios::trunc);
    out << "// Generated by tools/gen_unicode_lower.cpp - do not edit.\n"
           "// Unicode 16.0.0, data/UnicodeData-16.0.0.txt, SHA-256 ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f\n"
           "// mappings: " << mappings << "\n"
           "// lowerCodePoint(cp) = cp + kLowerStage2[kLowerStage1[cp >> 7] * 128 + (cp & 127)]\n";
    out << "constexpr uint16_t kLowerStage1[" << stage1.size() << "] = {";
    for (uint32_t b = 0; b < stage1.size(); ++b) out << (b % 32 == 0 ? "\n    " : " ") << stage1[b] << ",";
    out << "\n};\nconstexpr int32_t kLowerStage2[" << blocks.size() * kBlock << "] = {";
    for (uint32_t i = 0; i < blocks.size() * kBlock; ++i) out << (i % 16 == 0 ? "\n    " : " ") << blocks[i / kBlock][i % kBlock] << ",";
    out << "\n};\nconstexpr uint32_t kMaxLoweredLenBySrcLen[5] = {" << maxLen[0] << ", " << maxLen[1] << ", " << maxLen[2] << ", " << maxLen[3] << ", " << maxLen[4] << "};\n";
    if (!out) { std::fprintf(stderr, "write failed\n"); return 1; }
    return 0;
}
